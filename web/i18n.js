let current = 'zh-CN';

export function setLanguage(lang) {
  current = DICT[lang] ? lang : 'zh-CN';
  document.documentElement.lang = current;
  apply();
  return current;
}

export function getLanguage() { return current; }

export function t(key, fallback = '') {
  return DICT[current]?.[key] || DICT['zh-CN']?.[key] || DICT.en?.[key] || fallback || key;
}

export function apply(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    const key = node.dataset.i18n;
    const value = t(key);
    if (node.tagName === 'INPUT' || node.tagName === 'TEXTAREA') {
      node.placeholder = value;
      continue;
    }
    const textNodes = [...node.childNodes].filter((child) => child.nodeType === 3 && child.nodeValue.trim());
    if (textNodes.length) textNodes[0].nodeValue = value;
    else if (!node.children.length) node.textContent = value;
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    const value = t(node.dataset.i18nTitle);
    node.dataset.tip = value;
    node.setAttribute('aria-label', value);
    node.removeAttribute('title');
  }
  for (const node of root.querySelectorAll('[data-i18n-ph]')) {
    node.placeholder = t(node.dataset.i18nPh);
  }
}
